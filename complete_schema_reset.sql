-- A. Table: SERVICES
CREATE TABLE services (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    user_id UUID DEFAULT auth.uid() NOT NULL, -- Auto-assigns logged in user
    name TEXT NOT NULL,
    price NUMERIC NOT NULL DEFAULT 0,
    unit TEXT NOT NULL DEFAULT 'kg',
    category TEXT NOT NULL DEFAULT 'Cuci Komplit',
    image_url TEXT,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- B. Table: ORDERS
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID DEFAULT auth.uid() NOT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending', -- pending, processing, completed, paid
    total_price NUMERIC NOT NULL DEFAULT 0,
    items JSONB DEFAULT '[]'::jsonb, -- Legacy support for UI
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- C. Table: ORDER_ITEMS (Relational)
CREATE TABLE order_items (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
    service_name TEXT NOT NULL, -- Snapshot of service name
    service_price NUMERIC NOT NULL DEFAULT 0, -- Snapshot of price
    quantity NUMERIC NOT NULL DEFAULT 1,
    unit TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- D. Table: INVENTORY_ITEMS
CREATE TABLE inventory_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID DEFAULT auth.uid() NOT NULL,
    name TEXT NOT NULL,
    stock INT NOT NULL DEFAULT 0,
    unit TEXT NOT NULL,
    min_stock INT DEFAULT 5,
    category TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- E. Table: INVENTORY_LOGS
CREATE TABLE inventory_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID DEFAULT auth.uid() NOT NULL,
    inventory_item_id BIGINT REFERENCES inventory_items(id) ON DELETE CASCADE,
    change_amount INT NOT NULL,
    final_stock INT NOT NULL,
    change_type TEXT NOT NULL, -- restock, usage, correction, initial
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- F. Table: EXPENSES
CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID DEFAULT auth.uid() NOT NULL, -- Added ownership
    category TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    description TEXT,
    expense_date DATE DEFAULT CURRENT_DATE,
    payment_method TEXT DEFAULT 'Tunai',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

