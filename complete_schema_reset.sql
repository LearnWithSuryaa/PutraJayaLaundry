-- ==========================================
-- 5. SECURE VIEWS
-- ==========================================
CREATE VIEW monthly_stats_view WITH (security_invoker = true) AS
SELECT
    date_trunc('month', created_at) AS month,
    COUNT(id) AS total_orders,
    SUM(total_price) AS total_revenue
FROM
    orders
GROUP BY
    date_trunc('month', created_at);

